import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
export function flattenTokens(tree, prefix = '', inheritedType, output = new Map()) {
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$')) continue;
    if (/[.{}]/.test(key) || !node || typeof node !== 'object')
      throw new Error(`Invalid token key or group: ${prefix}${key}`);
    const path = prefix ? `${prefix}.${key}` : key,
      type = node.$type ?? inheritedType;
    if (Object.hasOwn(node, '$value')) {
      if (!type) throw new Error(`Missing type: ${path}`);
      output.set(path, { type, value: node.$value, description: node.$description ?? '' });
    } else flattenTokens(node, path, type, output);
  }
  return output;
}
export function resolveTokens(tree) {
  const tokens = flattenTokens(tree),
    resolved = new Map();
  function get(path, stack = []) {
    if (resolved.has(path)) return resolved.get(path);
    if (stack.includes(path))
      throw new Error('Circular token alias: ' + [...stack, path].join(' -> '));
    const token = tokens.get(path);
    if (!token) throw new Error('Unknown token: ' + path);
    let value = token.value;
    if (typeof value === 'string' && /^\{.+\}$/.test(value)) {
      const target = value.slice(1, -1),
        other = tokens.get(target);
      if (!other) throw new Error('Unknown token: ' + target);
      if (other.type !== token.type) throw new Error('Alias type mismatch: ' + path);
      value = get(target, [...stack, path]).value;
    }
    const output = { ...token, value, css: cssValue(token.type, value) };
    resolved.set(path, output);
    return output;
  }
  for (const path of tokens.keys()) get(path);
  return resolved;
}
export function cssValue(type, value) {
  const finite = (v) => typeof v === 'number' && Number.isFinite(v);
  if (type === 'color') {
    if (
      value?.colorSpace !== 'srgb' ||
      !Array.isArray(value.components) ||
      value.components.length !== 3 ||
      value.components.some((v) => !finite(v) || v < 0 || v > 1) ||
      !finite(value.alpha ?? 1) ||
      (value.alpha ?? 1) < 0 ||
      (value.alpha ?? 1) > 1
    )
      throw new Error('Expected normalized sRGB color');
    return `rgb(${value.components.map((v) => Math.round(v * 255)).join(' ')} / ${value.alpha ?? 1})`;
  }
  if (type === 'dimension' || type === 'duration') {
    if (
      !finite(value?.value) ||
      !(type === 'dimension' ? ['px', 'rem'] : ['ms', 's']).includes(value.unit)
    )
      throw new Error('Invalid ' + type);
    return `${value.value}${value.unit}`;
  }
  if (type === 'fontFamily') {
    const names = Array.isArray(value) ? value : [value];
    if (!names.length || names.some((n) => typeof n !== 'string' || /[;{}\n]/.test(n)))
      throw new Error('Invalid font family');
    return names.map((n) => (/\s/.test(n) ? JSON.stringify(n) : n)).join(', ');
  }
  if (type === 'number' || type === 'fontWeight') {
    if (!finite(value) || (type === 'fontWeight' && (value < 1 || value > 1000)))
      throw new Error('Invalid number');
    return String(value);
  }
  if (type === 'cubicBezier') {
    if (
      !Array.isArray(value) ||
      value.length !== 4 ||
      value.some((v) => !finite(v)) ||
      value[0] < 0 ||
      value[0] > 1 ||
      value[2] < 0 ||
      value[2] > 1
    )
      throw new Error('Invalid cubic-bezier');
    return `cubic-bezier(${value.join(', ')})`;
  }
  throw new Error('Unsupported token type: ' + type);
}
export function generate(tree) {
  const tokens = resolveTokens(tree),
    name = (path) => path.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()).replaceAll('.', '-');
  const common = [...tokens]
    .filter(([p]) => !p.startsWith('theme.'))
    .map(([p, t]) => `  --${name(p)}: ${t.css};`)
    .join('\n');
  let css = `/* Generated by scripts/tokens.mjs. Edit tokens/tickets.tokens.json, not this file. */\n:root {\n${common}\n}\n`;
  for (const mode of ['dark', 'light']) {
    const declarations = [...tokens]
      .filter(([p]) => p.startsWith('theme.' + mode + '.'))
      .map(([p, t]) => `  --color-${name(p.split('.').slice(2).join('.'))}: ${t.css};`)
      .join('\n');
    css += `${mode === 'dark' ? ':root, ' : ''}[data-theme="${mode}"] {\n${declarations}\n  color-scheme: ${mode};\n}\n`;
  }
  const manifest = Object.fromEntries(
    [...tokens].map(([p, t]) => [p, { type: t.type, value: t.value, css: t.css }]),
  );
  const ts =
    '// Generated. Do not edit.\nexport const tokens = ' +
    JSON.stringify(manifest, null, 2) +
    ' as const;\nexport type TokenName = keyof typeof tokens;\n';
  const md =
    '# Generated token reference\n\nSource: `tokens/tickets.tokens.json`. Run `bun run tokens:build`.\n\n| Token | Type | CSS |\n|---|---|---|\n' +
    [...tokens].map(([p, t]) => `| \`${p}\` | ${t.type} | \`${t.css}\` |`).join('\n') +
    '\n';
  return {
    'src/shared/styles/tokens.css': css,
    'src/shared/config/tokens.ts': ts,
    'docs/tokens.md': md,
  };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tree = JSON.parse(
    await readFile(new URL('../tokens/tickets.tokens.json', import.meta.url), 'utf8'),
  );
  const root = fileURLToPath(new URL('../', import.meta.url)),
    check = process.argv.includes('--check');
  for (const [file, content] of Object.entries(generate(tree))) {
    const path = resolve(root, file);
    if (check) {
      const actual = await readFile(path, 'utf8').catch(() => null);
      if (actual !== content) throw new Error('Generated tokens are stale: ' + file);
    } else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, content);
    }
  }
  console.log(
    check ? 'Tokens are valid and up to date.' : 'Generated CSS, TypeScript and token reference.',
  );
}
